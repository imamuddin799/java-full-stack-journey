package lambdaexpression_14.dec_26;

public class Car03 {

	String brand;
	double cost;
	int topSpeed;

	public Car03(String brand, double cost, int topSpeed) {
		this.brand = brand;
		this.cost = cost;
		this.topSpeed = topSpeed;
	}

	public String toString() {
		return "\nCar [brand=" + brand + ", cost=" + cost + ", topSpeed=" + topSpeed + "]";
	}
}