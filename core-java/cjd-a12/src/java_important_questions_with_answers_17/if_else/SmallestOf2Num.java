package java_important_questions_with_answers_17.if_else;

public class SmallestOf2Num {

	public static void main(String[] args) {
		int a = 10, b = 20;
		System.out.println("Given numbers are A : " + a + ", B : " + b);
		if (a < b) {
			System.out.println("Smallest of given 2 numbers : " + a);
		} else {
			System.out.println("Smallest of given 2 numbers : " + b);
		}
	}
}