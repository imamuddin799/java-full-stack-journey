package collection_13.list_01.arraylist_01.sorting.dec_25;

public class Student01 {

	int id;
	String name;
	double marks;

	public Student01(int id, String name, double marks) {
		this.id = id;
		this.name = name;
		this.marks = marks;
	}

	public String toString() {
		return "\nStudent [id=" + id + ", name=" + name + ", marks=" + marks + "]";
	}
}
