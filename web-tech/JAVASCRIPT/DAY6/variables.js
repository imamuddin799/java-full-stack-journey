//var keyword
var a;                  //declaration is possible
a = 10;                 //initialization is possible
console.log(a);
var a;                  //redeclaration is possible
a = 100;                //reinitialization is possible
console.log(a);

//let keyword
let b;                  //declaration is possible
b = 20;                 //initialization is possible
console.log(b);
// let b;               //redeclaration is not possible
b = 200                 //reinitialization is possible
console.log(b);


// const keyword
const c = 30;           //declaration and initialization is also possible in single line only
// const c;             //redeclaration is not possible
// c = 300;             //reinitialization is not possible